String fromUtf8(const String& text, size_t maxLen) {
  String out;
  const uint8_t* p = reinterpret_cast<const uint8_t*>(text.c_str());
  while (*p && out.length() < maxLen) {
    uint32_t cp;
    if (*p < 0x80) {
      cp = *p++;
    } else if ((*p & 0xE0) == 0xC0 && (p[1] & 0xC0) == 0x80) {
      cp = ((p[0] & 0x1F) << 6) | (p[1] & 0x3F);
      p += 2;
    } else if ((*p & 0xF0) == 0xE0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
      cp = ((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F);
      p += 3;
    } else {
      p++;
      while ((*p & 0xC0) == 0x80) p++;
      cp = '?';
    }
    String part = encode(cp);
    if (out.length() + part.length() > maxLen) break;
    out += part;
  }
  return out;
}

