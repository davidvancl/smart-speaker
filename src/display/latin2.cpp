struct Fallback {
  uint16_t cp;
  const char* text;
};

const Fallback FALLBACKS[] = {
    {0x2013, "-"}, {0x2014, "-"}, {0x2018, "'"}, {0x2019, "'"}, {0x201A, "'"}, {0x201C, "'"}, {0x201D, "'"},
    {0x201E, "'"}, {0x2026, "..."}, {0x00B7, "."}, {0x2022, "."}, {0x00E0, "a"}, {0x00E8, "e"}, {0x00EC, "i"},
    {0x00F2, "o"}, {0x00F9, "u"}, {0x00F1, "n"}, {0x00EA, "e"}, {0x00E5, "a"}, {0x00F8, "o"}, {0x00C0, "A"},
    {0x00C8, "E"}, {0x00D1, "N"}, {0x00C5, "A"}, {0x00D8, "O"}, {0x00E6, "ae"}, {0x00C6, "AE"},
};

String encode(uint32_t cp) {
  if (cp == '"') return "'";
  if (cp == '\\') return "/";
  if (cp == '\r' || cp == '\n' || cp == '\t') return " ";
  if (cp < 0x20) return "";
  if (cp < 0x80) return String(static_cast<char>(cp));
  for (uint8_t i = 0; i < 96; i++) {
    if (UPPER[i] == cp) return String(static_cast<char>(0xA0 + i));
  }
  for (const Fallback& f : FALLBACKS) {
    if (f.cp == cp) return f.text;
  }
  return "?";
}

